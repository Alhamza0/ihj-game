function buildSet(list) {
  const s = new Set();
  list.forEach(v => { const n = norm(v); if (n) s.add(n); });
  return s;
}

const SETS = {
  country: buildSet(COUNTRIES),
  city: buildSet(CITIES),
};

// الفئات التي لها قاموس مغلق
export const CLOSED_CATS = Object.keys(SETS);

// هل القيمة معروفة في قاموس الفئة؟ (للفئات المغلقة فقط)
export function inDictionary(cat, value) {
  const set = SETS[cat];
  if (!set) return false;
  return set.has(norm(value));
}
