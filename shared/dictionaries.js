export const CLOSED_CATS = Object.keys(SETS);
// الفئات الصارمة: القائمة شبه كاملة → يجوز رفض غير الموجود حتى بلا ذكاء (مع تجاوز المضيف).
export const STRICT_CATS = ["country"];

// هل القيمة معروفة في قاموس الفئة؟ (تتحقّق من الصيغتين: مع «ال» وبدونها)
export function inDictionary(cat, value) {
  const set = SETS[cat];
  if (!set) return false;
  return set.has(norm(value)) || set.has(stripAl(value));
}
